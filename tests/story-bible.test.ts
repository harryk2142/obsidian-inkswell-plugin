import { describe, expect, it } from "vitest";
import {
  CodexEntryData,
  STORY_BIBLE_MARKER,
  StoryBibleInput,
  StoryBibleSection,
  assembleStoryBible,
  codexEntryText,
} from "../src/plan/story-bible";
import type { MergedBeat } from "../src/outliner/beats";
import type { OutlineTree } from "../src/outliner/outline";

const ALL = new Set<StoryBibleSection>(["overview", "beats", "outline", "codex"]);
const only = (...s: StoryBibleSection[]) => new Set<StoryBibleSection>(s);

const scene = (title: string) => ({ title, path: `S/${title}.md`, indent: 0 });

const beat = (id: string, name: string, assignment: MergedBeat["assignment"]): MergedBeat => ({
  id,
  name,
  blurb: "generic template blurb",
  position: 10,
  assignment,
});

const ANNA: CodexEntryData = {
  name: "Anna",
  aliases: ["Annie"],
  image: "Art/anna.png",
  fields: [
    { label: "Role", type: "text", value: "Protagonist" },
    { label: "Age", type: "number", value: 34 },
    { label: "Backstory", type: "textarea", value: "Grew up by the docks.\nLeft at sixteen." },
    { label: "Traits", type: "list", value: ["stubborn", "kind"] },
    { label: "Relationships", type: "links", value: ["[[Ben|brother]]", "[[Cora]]"] },
    { label: "Home", type: "links", value: "[[Vesper Row]]" },
    { label: "Portrait", type: "image", value: "Art/anna.png" },
    { label: "Empty", type: "text", value: "" },
  ],
};

function input(over: Partial<StoryBibleInput> = {}): StoryBibleInput {
  const tree: OutlineTree = {
    acts: [
      {
        id: "a1",
        title: "Act I",
        chapters: [
          { id: "c1", title: "One", scenes: [scene("Arrival"), scene("Cut scene")] },
          { id: "c2", title: "Empty chapter", scenes: [] },
        ],
      },
    ],
    looseChapters: [{ id: "c3", title: "Interlude", scenes: [scene("Dream")] }],
    unassignedScenes: [scene("Stray")],
  };
  return {
    title: "Lamplight",
    generated: "2026-10-09",
    overview: {
      fields: [
        { label: "Logline", value: "A lamplighter keeps a city's memory." },
        { label: "Theme", value: "" },
      ],
      sections: [
        { heading: "Synopsis", text: "Mara lights lamps." },
        { heading: "Act II", text: "   " },
      ],
    },
    beats: {
      templateName: "Save the Cat",
      beats: [
        beat("opening", "Opening Image", { scenes: ["Arrival"], note: "Quiet night.", done: true }),
        beat("theme", "Theme Stated", {}),
      ],
    },
    outline: {
      tree,
      scenes: {
        Arrival: { pov: "Mara", synopsis: "She arrives.\nLate." },
        "Cut scene": { inactive: true, synopsis: "Gone" },
        Dream: {},
        Stray: { synopsis: "Loose end" },
      },
    },
    codex: [
      { label: "Characters", entries: [ANNA] },
      { label: "Locations", entries: [] },
    ],
    ...over,
  };
}

describe("assembleStoryBible", () => {
  it("starts with the marker, generated line, and title", () => {
    const md = assembleStoryBible(input(), ALL);
    expect(md.startsWith(STORY_BIBLE_MARKER)).toBe(true);
    expect(md).toContain("*Generated by Inkswell on 2026-10-09.");
    expect(md).toContain("# Lamplight — Story bible");
  });

  it("includes only the picked sections", () => {
    const md = assembleStoryBible(input(), only("codex"));
    expect(md).toContain("## Codex");
    expect(md).not.toContain("## Overview");
    expect(md).not.toContain("## Beat sheet");
    expect(md).not.toContain("## Outline");
  });

  it("skips empty overview fields and blank plan sections", () => {
    const md = assembleStoryBible(input(), only("overview"));
    expect(md).toContain("**Logline:** A lamplighter keeps a city's memory.");
    expect(md).not.toContain("Theme");
    expect(md).toContain("### Synopsis\n\nMara lights lamps.");
    expect(md).not.toContain("Act II");
  });

  it("beat sheet: filled beats only, no blurbs or done flags", () => {
    const md = assembleStoryBible(input(), only("beats"));
    expect(md).toContain("## Beat sheet — Save the Cat");
    expect(md).toContain("### Opening Image\n\n*Scenes: Arrival*\n\nQuiet night.");
    expect(md).not.toContain("Theme Stated");
    expect(md).not.toContain("blurb");
  });

  it("outline: acts › chapters › scenes, archived scenes and empty chapters left out", () => {
    const md = assembleStoryBible(input(), only("outline"));
    expect(md).toContain("### Act I\n\n#### One\n\n- **Arrival** *(POV: Mara)* — She arrives. Late.");
    expect(md).not.toContain("Cut scene");
    expect(md).not.toContain("Empty chapter");
    expect(md).toContain("### Chapters with no act\n\n#### Interlude\n\n- **Dream**");
    expect(md).toContain("### Unassigned scenes\n\n- **Stray** — Loose end");
  });

  it("outline without acts puts chapters at the act level, with no 'no act' heading", () => {
    const tree: OutlineTree = {
      acts: [],
      looseChapters: [{ id: "c1", title: "One", scenes: [scene("Arrival")] }],
      unassignedScenes: [],
    };
    const md = assembleStoryBible(input({ outline: { tree, scenes: {} } }), only("outline"));
    expect(md).toContain("## Outline\n\n### One\n\n- **Arrival**");
    expect(md).not.toContain("Chapters with no act");
  });

  it("codex: grouped by type, empty groups skipped, image embedded", () => {
    const md = assembleStoryBible(input(), only("codex"));
    expect(md).toContain("### Characters\n\n#### Anna\n\n![[Art/anna.png|240]]");
    expect(md).not.toContain("### Locations");
  });

  it("says so when nothing picked has content", () => {
    const md = assembleStoryBible(input({ beats: { templateName: "x", beats: [] } }), only("beats"));
    expect(md).toContain("*Nothing to show yet for the sections you picked.*");
  });
});

describe("codexEntryText", () => {
  it("plain text: readable lines, links as names, empty and image skipped", () => {
    expect(codexEntryText(ANNA, { title: true })).toBe(
      [
        "Anna",
        "Also known as: Annie",
        "Role: Protagonist",
        "Age: 34",
        "Backstory:\nGrew up by the docks.\nLeft at sixteen.",
        "Traits: stubborn, kind",
        "Relationships: Ben (brother), Cora",
        "Home: Vesper Row",
      ].join("\n")
    );
  });

  it("markdown: bold labels, blank lines between fields", () => {
    const md = codexEntryText(ANNA, { markdown: true });
    expect(md).toContain("**Also known as:** Annie\n\n**Role:** Protagonist");
    expect(md).not.toContain("**Anna**");
  });
});
